"""Generate anti-aliased VLW fonts for LovyanGFX from TrueType files.

Usage:  python tools/make_fonts.py
Writes: firmware/SkyDisplay/fonts.h

VLW layout (big-endian int32): header = glyph count, version 11, size, 0, ascent, descent;
then per glyph 7 ints = codepoint, height, width, x advance, top (dY from baseline), left (dX), 0;
then each glyph's 8-bit alpha bitmap (width * height bytes), in the same order.
"""
import os, struct
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "firmware", "SkyDisplay", "fonts.h")
FONT_DIR = os.path.join(HERE, "fonts")

# (C name, TTF weight, pixel size)
FONTS = [
    ("F_SMALL",  "SemiBold", 15),   # chart labels, hour labels, tile labels, footer labels
    ("F_BODY",   "Medium",   18),   # secondary lines, header status, footer values
    ("F_BODYB",  "SemiBold", 21),   # tile detail line, header date
    ("F_TITLE",  "SemiBold", 26),   # full-screen message titles
    ("F_BIG",    "Bold",     36),   # verdict words
    ("F_HUGE",   "Bold",     48),   # outside temperature on the weather screen
]
CHARS = [chr(c) for c in range(0x20, 0x7F)] + ["°", "·", "–", "≤", "≥"]


def vlw(ttf_path, px):
    font = ImageFont.truetype(ttf_path, px)
    ascent, descent = font.getmetrics()
    heads, bitmaps = [], []
    for ch in CHARS:
        adv = int(round(font.getlength(ch)))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")  # relative to the baseline origin
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        if w == 0 or h == 0:          # space and other blanks
            heads.append((ord(ch), 0, 0, adv, 0, 0, 0)); bitmaps.append(b""); continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        heads.append((ord(ch), h, w, adv, -y0, x0, 0)); bitmaps.append(img.tobytes())
    data = struct.pack(">6i", len(CHARS), 11, px, 0, ascent, descent)
    for hd in heads: data += struct.pack(">7i", *hd)
    for bm in bitmaps: data += bm
    return data


def main():
    lines = ["#pragma once", "// Generated by tools/make_fonts.py from Barlow Semi Condensed (SIL OFL 1.1, see tools/fonts/OFL.txt).",
             "// Do not edit by hand.", "#include <stdint.h>", ""]
    total = 0
    for name, weight, px in FONTS:
        data = vlw(os.path.join(FONT_DIR, f"BarlowSemiCondensed-{weight}.ttf"), px)
        total += len(data)
        lines.append(f"// {weight} {px}px, {len(data)} bytes")
        lines.append(f"static const uint8_t {name}[] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}: {len(FONTS)} fonts, {total} bytes")


if __name__ == "__main__":
    main()
